#!/usr/bin/env bash
# Refreshes deploy/cloudflare-ips.txt from Cloudflare's own published lists, then regenerates
# the two Caddy-syntax snippets derived from it (deploy/cloudflare/*.caddy) AND the same two
# snippets for prod (deploy-prod/cloudflare/*.caddy, docs/plans/prod-deploy.md §3 Session 2).
# Cloudflare's published IP ranges are global, not per-zone, so this one fetch feeds both
# environments — there is no separate "prod ranges" to fetch. Run this on either VPS (or anywhere,
# then copy the output files over) whenever Cloudflare rotates its ranges — rare, but Cloudflare
# recommends checking periodically. Never hand-edit any of the generated files; they are
# regenerated here, not maintained separately.
#
# docs/plans/deploy-dev.md: this is defense-in-depth only (logging accuracy + an extra IP check)
# — the actual Cloudflare trust boundary is each environment's own Caddyfile's Authenticated
# Origin Pulls (client_auth), which doesn't depend on this list being perfectly current.
set -euo pipefail
cd "$(dirname "$0")"

tmp_v4="$(mktemp)"
tmp_v6="$(mktemp)"
trap 'rm -f "$tmp_v4" "$tmp_v6"' EXIT

curl -fsSL https://www.cloudflare.com/ips-v4 -o "$tmp_v4"
curl -fsSL https://www.cloudflare.com/ips-v6 -o "$tmp_v6"

{
  echo "# Cloudflare published IP ranges — refreshed $(date -u +%Y-%m-%dT%H:%M:%SZ) by"
  echo "# deploy/update-cloudflare-ips.sh. Source: https://www.cloudflare.com/ips-v4 and"
  echo "# https://www.cloudflare.com/ips-v6 — do not hand-edit, re-run the script instead."
  # Cloudflare's ips-v4 file has no trailing newline — without the explicit `echo` here, the
  # last v4 range and the first v6 range would land on the same line with no separator between
  # them (caught by actually running this script: produced the corrupted single CIDR entry
  # "131.0.72.0/222400:cb00::/32").
  cat "$tmp_v4"
  echo
  cat "$tmp_v6"
} > cloudflare-ips.txt

ranges="$(grep -v '^#' cloudflare-ips.txt | tr '\n' ' ' | sed 's/ *$//')"

mkdir -p cloudflare
{
  echo "# GENERATED by deploy/update-cloudflare-ips.sh from ../cloudflare-ips.txt — do not"
  echo "# hand-edit; re-run that script instead. Imported as a top-level snippet by ../Caddyfile."
  echo "(cloudflare_only) {"
  echo "	@not_cloudflare not remote_ip ${ranges}"
  echo "	respond @not_cloudflare \"\" 403"
  echo "}"
} > cloudflare/cloudflare-only.caddy

{
  echo "# GENERATED by deploy/update-cloudflare-ips.sh from ../cloudflare-ips.txt — do not"
  echo "# hand-edit; re-run that script instead. Imported into ../Caddyfile's global options block."
  echo "servers {"
  echo "	trusted_proxies static ${ranges}"
  echo "}"
} > cloudflare/trusted-proxies.caddy

# Prod destination (deploy-prod/, a sibling of deploy/ — docs/plans/prod-deploy.md §2 "Config
# location" row). Prod gets its own verbatim copy of cloudflare-ips.txt (not a symlink — this
# script may run on a machine/VPS with only one of the two trees checked out) so that its own
# snippets' "../cloudflare-ips.txt" header comments below point at a file that actually exists
# next to them, exactly like dev's. Same $ranges computed once above — one fetch, two
# destinations, byte-identical snippet bodies in both places (only the hand-written header
# wording differs from dev's, which is unchanged above).
prod_dir="../deploy-prod"
if [ -d "$prod_dir" ]; then
  cp cloudflare-ips.txt "$prod_dir/cloudflare-ips.txt"
  mkdir -p "$prod_dir/cloudflare"

  {
    echo "# GENERATED by deploy/update-cloudflare-ips.sh from ../cloudflare-ips.txt — do not"
    echo "# hand-edit; re-run that script instead. Imported as a top-level snippet by ../Caddyfile."
    echo "(cloudflare_only) {"
    echo "	@not_cloudflare not remote_ip ${ranges}"
    echo "	respond @not_cloudflare \"\" 403"
    echo "}"
  } > "$prod_dir/cloudflare/cloudflare-only.caddy"

  {
    echo "# GENERATED by deploy/update-cloudflare-ips.sh from ../cloudflare-ips.txt — do not"
    echo "# hand-edit; re-run that script instead. Imported into ../Caddyfile's global options block."
    echo "servers {"
    echo "	trusted_proxies static ${ranges}"
    echo "}"
  } > "$prod_dir/cloudflare/trusted-proxies.caddy"

  echo "Wrote cloudflare-ips.txt, cloudflare/cloudflare-only.caddy, cloudflare/trusted-proxies.caddy (deploy/ and deploy-prod/)"
  echo "Next: 'caddy validate --config deploy/Caddyfile' and 'caddy validate --config deploy-prod/Caddyfile' on a machine/container with Caddy installed, then redeploy."
else
  echo "Wrote cloudflare-ips.txt, cloudflare/cloudflare-only.caddy, cloudflare/trusted-proxies.caddy"
  echo "deploy-prod/ not found next to deploy/ — skipped writing prod's copies; re-run from a full checkout to refresh them too."
  echo "Next: 'caddy validate --config deploy/Caddyfile' on a machine/container with Caddy installed, then redeploy."
fi
