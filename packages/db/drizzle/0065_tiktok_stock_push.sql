CREATE FUNCTION tiktok_stock_dirty_from_reservation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    PERFORM tiktok_stock_mark_dirty(OLD.sku, 'hold');
  END IF;
