CREATE FUNCTION tiktok_stock_mark_dirty(p_sku text, p_source text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF p_sku IS NOT NULL AND EXISTS (SELECT 1 FROM tiktok_shop_connections WHERE stock_sync_enabled) THEN
    INSERT INTO tiktok_stock_outbox (variant_sku, source) VALUES (p_sku, p_source);
  END IF;
END;
$$;--> statement-breakpoint
