-- The variants a stored TikTok order's snapshot names, through the active mappings (R2: a held TikTok
-- sale lowers the target). Lines that cannot be read (no list, an empty one, a non-object line) take
-- every mapped variant, the same fail-closed rule as tiktokHeldOrderQuantities: while such an order is
-- held every push holds, and when it stops being held everything is re-queued.
CREATE FUNCTION tiktok_stock_mark_snapshot_dirty(p_snapshot uuid) RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  lines jsonb;
BEGIN
  IF p_snapshot IS NULL OR NOT EXISTS (SELECT 1 FROM tiktok_shop_connections WHERE stock_sync_enabled) THEN
    RETURN;
  END IF;
  SELECT payload->'line_items' INTO lines FROM tiktok_order_snapshots WHERE id = p_snapshot;
  IF lines IS NULL OR jsonb_typeof(lines) <> 'array' OR jsonb_array_length(lines) = 0
     OR EXISTS (SELECT 1 FROM jsonb_array_elements(lines) li WHERE jsonb_typeof(li) <> 'object') THEN
    INSERT INTO tiktok_stock_outbox (variant_sku, source)
      SELECT DISTINCT variant_sku, 'tiktok_order' FROM tiktok_sku_mappings WHERE is_active;
  ELSE
    INSERT INTO tiktok_stock_outbox (variant_sku, source)
      SELECT DISTINCT m.variant_sku, 'tiktok_order'
      FROM jsonb_array_elements(lines) li
      JOIN tiktok_sku_mappings m ON m.is_active AND m.tiktok_sku_id = li->>'sku_id';
  END IF;
END;
$$;--> statement-breakpoint
CREATE FUNCTION tiktok_stock_dirty_from_tiktok_order() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.latest_snapshot_id IS DISTINCT FROM NEW.latest_snapshot_id THEN
    PERFORM tiktok_stock_mark_snapshot_dirty(OLD.latest_snapshot_id);
  END IF;
  PERFORM tiktok_stock_mark_snapshot_dirty(NEW.latest_snapshot_id);
  RETURN NULL;
END;
$$;--> statement-breakpoint
