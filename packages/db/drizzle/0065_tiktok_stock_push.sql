-- TikTok stock sync, S2 (docs/plans/tiktok-stock-sync.md §7): the push. Two new tables and the triggers
-- that fill the first one:
--   tiktok_stock_outbox        insert-only dirty-variant marks, written in the SAME transaction as every
--                              change that can move a variant's target quantity;
--   tiktok_stock_push_retries  per-variant retry state (backoff), written only by the push;
-- and two new cursor resources: `stock_push` (the drain's health; window_end = how far hold expiries were
-- queued) and `stock_reconcile` (the hourly full reconciliation).
--
-- Generated by drizzle-kit, then read line by line. HAND-AUTHORED: this header, the lock_timeout line and
-- everything after the cursor CHECK (the functions and triggers; drizzle-kit does not emit triggers, the
-- 0057/0063/0064 pattern).
--
-- Why triggers: no write path can forget the outbox, including ones added later (a new stock writer, a
-- raw INSERT in a script): stock_movements (every sale, cancellation, return, goods receipt, production
-- output, opname, adjustment, TikTok/Shopee apply), stock_reservations (checkout hold create, consume,
-- release, the payment sweep), tiktok_sku_mappings (map, unmap, auto-map), tiktok_orders (the R2 inputs:
-- a held TikTok sale appearing, being applied, cancelled or changing lines). A hold that merely EXPIRES
-- writes nothing; the cron queues those (`expires_at` since the last drain), not this file.
--
-- Insert-only, never ON CONFLICT DO UPDATE: a stock write never waits on (or deadlocks with) a row lock
-- the push or another writer holds; the push deletes by id up to what it read, so a mark committed
-- while it pushed survives. Marks are written only while a connection has the stock switch on (one
-- EXISTS per row); turning the switch on queues every mapped variant itself (application code), and
-- the cron re-queues everything right after a switch-on, so a stock write racing the switch is covered.
--
-- Backward compatibility with the previous release (CLAUDE.md expand/contract): additive only. The
-- previous release never reads the new tables or cursor rows; its writes keep working and, while its
-- switch is on, also leave marks (bounded by its writes; the next release drains them). The cursor CHECK
-- becomes a superset (dropped and re-added in this one transaction, the 0040/0064 pattern). No
-- reference data (sources are CHECK values). Locks: CREATE TRIGGER takes a short SHARE ROW EXCLUSIVE
-- lock on four tables; lock_timeout fails fast (and rolls back) instead of queueing behind traffic.

